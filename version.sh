# Версия и имя файла сборки — единственное место, где они задаются.

# Совпадает с android:versionName в AndroidManifest.xml; build.sh это проверяет.
VERSION="0.9.16-bridge"

# Номер сборки: в CI — номер прогона (растёт сам), локально — дата и время.
if [ -n "${GITHUB_RUN_NUMBER:-}" ]; then
    BUILD_NUM="${GITHUB_RUN_NUMBER}"
else
    BUILD_NUM="$(date -u +%m%d%H%M)"
fi

# Имя файла намеренно короткое и по форме совпадает с пакетами, которые на
# этом ГУ уже ставились: q50dash-1.1.epk и q50info-1.8.epk (по 15 символов).
# Длинное "Q50-GTR-Plus-v0.7-live-test-b58.epk" — 35 символов — AppManager не
# увидел вовсе ("No app file found"), поэтому длину держим близкой к
# проверенной. Номер сборки в конце делает имя уникальным: файл с уже
# виденным именем ГУ в списке не показывает.
ARTIFACT_BASE="q50gtr-0.9.${BUILD_NUM}"
